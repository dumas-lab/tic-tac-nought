import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const root = process.cwd();
const dist = path.join(root, "dist", "web");
const pkg = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));

const onlineArg = process.argv.slice(2).find((arg) => arg.startsWith("--online="));
const onlineMode = onlineArg ? onlineArg.slice("--online=".length) : "off";
if (!["off", "test", "live"].includes(onlineMode)) {
  console.error(`Unknown --online value "${onlineMode}". Use --online=test or --online=live.`);
  process.exit(1);
}

async function loadLocalEnv() {
  let text = "";
  try {
    text = await readFile(path.join(root, ".env.supabase.local"), "utf8");
  } catch {
    return;
  }
  for (const line of text.split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!match) continue;
    if (process.env[match[1]] !== undefined) continue;
    let value = match[2];
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[match[1]] = value;
  }
}

let onlineConfig = {
  enabled: false,
  supabaseUrl: "",
  supabaseAnonKey: "",
  version: pkg.version
};
let supabaseOrigin = "";

if (onlineMode !== "off") {
  await loadLocalEnv();
  const prefix = onlineMode === "test" ? "TTN_TEST" : "TTN_LIVE";
  const url = String(process.env[`${prefix}_SUPABASE_URL`] || "").trim().replace(/\/+$/, "");
  const key = String(process.env[`${prefix}_SUPABASE_KEY`] || "").trim();
  if (!url || !key) {
    console.error(`Missing ${prefix}_SUPABASE_URL or ${prefix}_SUPABASE_KEY for --online=${onlineMode}.`);
    process.exit(1);
  }
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    console.error(`${prefix}_SUPABASE_URL is not a valid URL.`);
    process.exit(1);
  }
  if (parsed.protocol !== "https:") {
    console.error(`${prefix}_SUPABASE_URL must use https.`);
    process.exit(1);
  }
  if (/service_role|sb_secret_/i.test(key)) {
    console.error(`${prefix}_SUPABASE_KEY looks like a service-role key. Use the public anon/publishable key.`);
    process.exit(1);
  }
  supabaseOrigin = parsed.origin;
  onlineConfig = {
    enabled: true,
    supabaseUrl: url,
    supabaseAnonKey: key,
    version: pkg.version
  };
}

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

await cp(path.join(root, "index.html"), path.join(dist, "index.html"));
await cp(path.join(root, "assets"), path.join(dist, "assets"), { recursive: true });
await cp(path.join(root, "web", "manifest.json"), path.join(dist, "manifest.json"));
await cp(path.join(root, "web", "pwa.js"), path.join(dist, "pwa.js"));
await cp(path.join(root, "online.js"), path.join(dist, "online.js"));
await cp(path.join(root, "canvas.js"), path.join(dist, "canvas.js"));

for (const page of ["privacy.html", "terms.html"]) {
  try {
    await cp(path.join(root, page), path.join(dist, page));
  } catch {
    console.warn(`Warning: ${page} is missing; the online build will link to a 404.`);
  }
}

await writeFile(
  path.join(dist, "online-config.js"),
  `/* Generated by scripts/build-web.mjs for ${onlineMode === "off" ? "local-only" : onlineMode} use. */\n` +
    `window.TTN_ONLINE_CONFIG = Object.freeze(${JSON.stringify(onlineConfig, null, 2)});\n`
);

await cp(path.join(root, "web", "icons"), path.join(dist, "icons"), { recursive: true });

let index = await readFile(path.join(dist, "index.html"), "utf8");
const scriptHashes = [];
const inlineScript = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;
for (const match of index.matchAll(inlineScript)) {
  if (!match[1].trim()) continue;
  scriptHashes.push(`sha256-${createHash("sha256").update(match[1], "utf8").digest("base64")}`);
}

const connectSrc = ["'self'", supabaseOrigin].filter(Boolean).join(" ");
const cspDirectives = [
  "default-src 'self'",
  `script-src 'self' ${scriptHashes.map((hash) => `'${hash}'`).join(" ")}`.trim(),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "media-src 'self'",
  `connect-src ${connectSrc}`,
  "font-src 'self'",
  "manifest-src 'self'",
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "upgrade-insecure-requests"
];
const csp = cspDirectives.join("; ");
const headerCsp = [...cspDirectives, "frame-ancestors 'none'"].join("; ");

const escapedCsp = csp.replaceAll("&", "&amp;").replaceAll('"', "&quot;");
const cspMeta = `<meta http-equiv="Content-Security-Policy" content="${escapedCsp}">`;
if (!index.includes('http-equiv="Content-Security-Policy"')) {
  index = index.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n${cspMeta}`);
}
await writeFile(path.join(dist, "index.html"), index);
await writeFile(path.join(dist, "csp.txt"), headerCsp + "\n");
await writeFile(path.join(dist, "_headers"), `/*
  Content-Security-Policy: ${headerCsp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
`);
await writeFile(path.join(dist, ".nojekyll"), "");

const files = [];
async function walk(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) await walk(path.join(dir, entry.name), rel);
    else files.push(rel);
  }
}
await walk(dist);
files.sort();

const skipped = new Set(["sw.js", "_headers", "csp.txt", ".nojekyll"]);
const precache = ["./", ...files.filter((file) => !skipped.has(file)).map((file) => `./${file}`)];
const swTemplate = await readFile(path.join(root, "web", "sw.template.js"), "utf8");
const sw = swTemplate
  .replaceAll("__VERSION__", pkg.version)
  .replace("__PRECACHE__", JSON.stringify(precache, null, 2));
await writeFile(path.join(dist, "sw.js"), sw);

const total = (await Promise.all(files.map(async (file) => (await stat(path.join(dist, file))).size))).reduce((a, b) => a + b, 0);
console.log(`Web build ${pkg.version} (${onlineMode === "off" ? "local-only" : onlineMode}): ${files.length} files, ${(total / 1024 / 1024).toFixed(2)} MiB, ${precache.length} precached.`);
console.log(`CSP script hashes: ${scriptHashes.length}${supabaseOrigin ? `, connect-src ${supabaseOrigin}` : ""}`);
